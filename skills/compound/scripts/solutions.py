"""Capture local solutions, build their index, and search a bounded shortlist."""
from __future__ import annotations

import argparse
from contextlib import ExitStack, contextmanager, suppress
import html
import os
from pathlib import Path
import re
import secrets
import stat
import sys
import tomllib

try:
    from .safe_open import open_regular_nofollow
except ImportError:  # Direct script execution.
    from safe_open import open_regular_nofollow


SOLUTIONS = Path('docs/solutions')
INDEX = 'INDEX.md'
MARKER = '<!-- Generated by Compound solutions. -->'
TABLE = ('| Problem | Tags | File Path |', '|---|---|---|')
MAX_INDEX_BYTES = 1024 * 1024
MAX_METADATA_BYTES = 8192
MAX_CAPTURE_BYTES = 8192
MAX_ENTRIES = 4096
MAX_DEPTH = 16
MAX_RESULTS = 5
DEFAULT_LIMIT = 3
MAX_OUTPUT_BYTES = 1024
MAX_NOTE_OUTPUT_BYTES = 2048
WORD = re.compile(r'[^\W_]+')
CAPTURE_NAME = re.compile(r'[a-z0-9]+(?:-[a-z0-9]+)*\.md')


def _bounded_read(source, limit: int) -> bytes:
    data = source.read(limit + 1)
    if len(data) > limit:
        raise ValueError('solutions index exceeds its byte limit')
    return data


@contextmanager
def _solutions_directory(root: Path, *, create: bool = False):
    """Pin and lock the output directory without following repository links."""
    if not hasattr(os, 'O_NOFOLLOW') or os.open not in os.supports_dir_fd:
        raise ValueError('safe directory access is unavailable on this platform')
    from fcntl import LOCK_EX, flock

    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
    with ExitStack() as stack:
        directory = os.open(root, flags)
        stack.callback(os.close, directory)
        for part in SOLUTIONS.parts:
            try:
                if create:
                    with suppress(FileExistsError):
                        os.mkdir(part, dir_fd=directory)
                child = os.open(part, flags, dir_fd=directory)
            except OSError as error:
                raise ValueError('docs/solutions is missing or unsafe; use a real directory') from error
            directory = child
            stack.callback(os.close, directory)
        flock(directory, LOCK_EX)
        yield directory


def _open_file(directory: int, name: str):
    fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory)
    if not stat.S_ISREG(os.fstat(fd).st_mode):
        os.close(fd)
        raise ValueError(f'unsafe non-regular file: {name}')
    return os.fdopen(fd, 'rb')


def _metadata(data: bytes, name: str) -> tuple[str, str]:
    lines = data.removeprefix(b'\xef\xbb\xbf').splitlines()
    try:
        if not lines or lines[0] != b'+++':
            raise ValueError
        end = lines.index(b'+++', 1)
        frontmatter = tomllib.loads(b'\n'.join(lines[1:end]).decode('utf-8'))
        problem, tags = frontmatter['problem'], frontmatter['tags']
        if not _valid_cell(problem, 256) or not isinstance(tags, list) or len(tags) > 12:
            raise ValueError
        if not all(_valid_cell(tag, 48) for tag in tags):
            raise ValueError
    except (ValueError, KeyError, RecursionError):
        raise ValueError(f'{name}: expected bounded TOML frontmatter with problem and tags') from None
    return problem.strip(), ', '.join(tag.strip() for tag in tags)


def _valid_cell(value, maximum: int) -> bool:
    return (isinstance(value, str) and bool(value.strip()) and len(value) <= maximum
            and all(character.isprintable() for character in value))


def _valid_path(value: str) -> bool:
    parts = value.split('/')
    return (_valid_cell(value, 512) and '\\' not in value
            and tuple(parts[:2]) == SOLUTIONS.parts and len(parts) > 2
            and all(part not in ('', '.', '..') for part in parts)
            and parts[-1].lower().endswith('.md') and value != (SOLUTIONS / INDEX).as_posix())


def _row(problem: str, tags: str, path: str) -> str:
    cells = (html.escape(cell, quote=False).replace('|', '&#124;') for cell in (problem, tags, path))
    return '| ' + ' | '.join(cells) + ' |'


def _raise_walk_error(error: OSError) -> None:
    raise error


def _note_rows(directory: int, *, reserved_entries: int = 0) -> list[tuple[str, str, str]]:
    rows = []
    entries = reserved_entries
    for subdir, dirs, files, subdir_fd in os.fwalk('.', dir_fd=directory, follow_symlinks=False, onerror=_raise_walk_error):
        entries += len(dirs) + len(files)
        relative = Path(subdir)
        if entries > MAX_ENTRIES or len(relative.parts) > MAX_DEPTH:
            raise ValueError('solutions directory exceeds its entry or nesting limit')
        for name in files:
            if not name.lower().endswith('.md') or (relative == Path('.') and name == INDEX):
                continue
            path = (SOLUTIONS / relative / name).as_posix()
            if not _valid_path(path):
                raise ValueError('solution note has an unsupported path')
            with _open_file(subdir_fd, name) as source:
                problem, tags = _metadata(source.read(MAX_METADATA_BYTES), name)
            rows.append((problem, tags, path))
    return rows


def _current_index(directory: int) -> tuple[bytes, int] | None:
    try:
        with _open_file(directory, INDEX) as source:
            data = _bounded_read(source, MAX_INDEX_BYTES)
            if not data.startswith((MARKER + '\n').encode()):
                raise ValueError('docs/solutions/INDEX.md is unmanaged; preserve it before generating an index')
            return data, stat.S_IMODE(os.fstat(source.fileno()).st_mode)
    except FileNotFoundError:
        return None


def _index_data(rows: list[tuple[str, str, str]]) -> bytes:
    ordered = sorted(rows, key=lambda row: (row[0].casefold(), row[2]))
    data = ('\n'.join([MARKER, *TABLE, *(_row(*row) for row in ordered)]) + '\n').encode()
    if len(data) > MAX_INDEX_BYTES:
        raise ValueError('solutions index exceeds its byte limit')
    return data


def _publish_file(directory: int, name: str, data: bytes, index_before: tuple[bytes, int] | None = None):
    """Create a complete file exclusively, or replace the checked managed index."""
    if index_before is not None and data == index_before[0]:
        return
    mode = index_before[1] if index_before is not None else 0o644
    pending = '.compound-pending-' + secrets.token_hex(8)
    fd = os.open(pending, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode, dir_fd=directory)
    try:
        with os.fdopen(fd, 'wb') as stream:
            if index_before is not None:
                os.fchmod(stream.fileno(), mode)
            stream.write(data)
        if index_before is None:
            os.link(pending, name, src_dir_fd=directory, dst_dir_fd=directory, follow_symlinks=False)
        else:
            if _current_index(directory) != index_before:
                raise ValueError('INDEX.md changed during refresh; retry with the current index')
            os.replace(pending, name, src_dir_fd=directory, dst_dir_fd=directory)
    finally:
        with suppress(FileNotFoundError):
            os.unlink(pending, dir_fd=directory)


def index_repository(root: Path) -> int:
    with _solutions_directory(root) as directory:
        existing = _current_index(directory)
        rows = _note_rows(directory)
        _publish_file(directory, INDEX, _index_data(rows), existing)
    return len(rows)


def capture_repository(root: Path, name: str, data: bytes) -> tuple[int, int, str]:
    """Save a note and return the index count, note word count, and index row."""
    if len(name) > 96 or not CAPTURE_NAME.fullmatch(name) or name == 'index.md':
        raise ValueError('use a lowercase note name such as retry-timeout.md')
    if len(data) > MAX_CAPTURE_BYTES:
        raise ValueError('solution note exceeds its byte limit')
    text = data.decode('utf-8')
    problem, tags = _metadata(data, name)
    path = (SOLUTIONS / name).as_posix()
    row = (problem, tags, path)
    with _solutions_directory(root, create=True) as directory:
        existing = _current_index(directory)
        try:
            with _open_file(directory, name) as source:
                if source.read(len(data) + 1) != data:
                    raise ValueError(f'{path} already exists with different content')
            create = False
        except FileNotFoundError:
            create = True
        rows = _note_rows(directory, reserved_entries=int(create) + int(existing is None))
        if create:
            rows.append(row)
        else:
            existing_row = next((row for row in rows if row[2] == path), None)
            if existing_row is None:
                raise ValueError(f'{path} already exists with different casing')
            row = existing_row
        index = _index_data(rows)
        if create:
            _publish_file(directory, name, data)
        try:
            _publish_file(directory, INDEX, index, existing)
        except (OSError, ValueError) as error:
            raise ValueError(f'{path} is saved; index refresh failed: {error}') from error
    return len(rows), len(text.split()), _row(*row)


def _search_rows(text: str, query: str, limit: int) -> tuple[str, str | None]:
    if not 1 <= limit <= MAX_RESULTS:
        raise ValueError('search limit must be between 1 and 5')
    if len(query) > 256:
        raise ValueError('query exceeds 256 characters')
    terms = set(WORD.findall(query.casefold()))
    if not terms:
        raise ValueError('provide at least one search term')
    lines = text.splitlines()
    if lines[:3] != [MARKER, *TABLE]:
        raise ValueError('INDEX.md is not a generated solutions index')
    exact, related = [], []
    for line in lines[3:]:
        cells = line.split('|')
        if len(cells) != 5 or cells[0] or cells[-1]:
            raise ValueError('invalid row in INDEX.md')
        problem, tags, path = (html.unescape(cell.strip()) for cell in cells[1:4])
        if not _valid_path(path) or not _valid_cell(problem, 256) or (tags and not _valid_cell(tags, 600)):
            raise ValueError('unsafe metadata or path in INDEX.md')
        words = [set(WORD.findall(cell.casefold())) for cell in (problem, tags, path)]
        matched = terms & set.union(*words)
        if matched == terms:
            matches = exact
        elif len(terms & words[1]) >= 2:
            matches = related
        else:
            continue
        score = sum(weight * len(terms & field) for weight, field in zip((3, 2, 1), words))
        matches.append((-len(matched), -score, problem.casefold(), path, _row(problem, tags, path)))
    hits = exact or related
    output = '\n'.join(TABLE) + '\n'
    count = 0
    first = None
    for _, _, _, path, row in sorted(hits):
        if len((output + row + '\n').encode()) <= MAX_OUTPUT_BYTES:
            output += row + '\n'
            if first is None:
                first = path
            count += 1
            if count == limit:
                break
    if first is None:
        message = 'No matches fit the output limit.\n' if hits else 'No matching solutions.\n'
        return message, None
    return output, first


def search_repository(root: Path, query: str, limit: int, *, show_note: bool = False) -> str:
    relative = (SOLUTIONS / INDEX).as_posix()
    try:
        with os.fdopen(open_regular_nofollow(root, relative), 'rb') as source:
            text = _bounded_read(source, MAX_INDEX_BYTES).decode('utf-8')
    except FileNotFoundError:
        raise ValueError('docs/solutions/INDEX.md is missing') from None
    output, first = _search_rows(text, query, limit)
    if not show_note or first is None:
        return output
    header = f'{output}\nNote: {first}\n\n'
    remaining = MAX_NOTE_OUTPUT_BYTES - len(header.encode())
    try:
        with os.fdopen(open_regular_nofollow(root, first), 'rb') as source:
            data = source.read(remaining + 1)
        if len(data) > remaining:
            return output + '\nMatching note exceeds the output limit.\n'
        return header + data.decode('utf-8')
    except (OSError, UnicodeError):
        return output + '\nMatching note unavailable.\n'


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    index = commands.add_parser('index', help='refresh the generated index')
    search = commands.add_parser('search', help='query the generated index')
    capture = commands.add_parser('capture', help='save a new Markdown note from stdin and refresh the index')
    for command in (index, search, capture):
        command.add_argument('--repo', type=Path, default=Path('.'))
    capture.add_argument('--name', required=True)
    search.add_argument('--query', required=True)
    search.add_argument('--show-note', action='store_true', help='include the first matching note if it fits')
    search.add_argument('--limit', type=int, choices=range(1, MAX_RESULTS + 1), default=DEFAULT_LIMIT)
    args = parser.parse_args(argv)
    try:
        root = args.repo.expanduser().resolve(strict=True)
        if args.command == 'index':
            print(f'docs/solutions/INDEX.md ({index_repository(root)} notes)')
        elif args.command == 'capture':
            count, words, row = capture_repository(root, args.name, sys.stdin.buffer.read(MAX_CAPTURE_BYTES + 1))
            unit = 'note' if count == 1 else 'notes'
            print(f'Saved docs/solutions/{args.name} and refreshed docs/solutions/INDEX.md ({count} {unit}).')
            print(f'Captured note has {words} words. Indexed entry:\n{row}')
        else:
            sys.stdout.write(search_repository(root, args.query, args.limit, show_note=args.show_note))
    except (OSError, ValueError, RuntimeError) as error:
        print(f'Solutions index unavailable. {error}', file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
